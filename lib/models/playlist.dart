import 'song.dart';

class Playlist {
  final String id;
  final String userId;
  final String name;
  final String description;
  final String coverUrl;
  final List<Song> tracks;
  final bool isAutoGenerated;
  final String recommendationReason;
  final double createdAt;
  final double updatedAt;

  const Playlist({
    required this.id,
    this.userId = '',
    required this.name,
    this.description = '',
    this.coverUrl = 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=600&q=80',
    this.tracks = const [],
    this.isAutoGenerated = false,
    this.recommendationReason = '',
    this.createdAt = 0,
    this.updatedAt = 0,
  });

  factory Playlist.fromJson(Map<String, dynamic> json) {
    final rawTracks = json['tracks'] as List<dynamic>? ?? [];
    final parsedTracks = rawTracks
        .whereType<Map<String, dynamic>>()
        .map((t) => Song.fromJson(t))
        .toList();

    return Playlist(
      id: json['id'] as String? ?? '',
      userId: json['userId'] as String? ?? '',
      name: json['name'] as String? ?? 'Untitled Playlist',
      description: json['description'] as String? ?? '',
      coverUrl: json['coverUrl'] as String? ??
          'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=600&q=80',
      tracks: parsedTracks,
      isAutoGenerated: json['isAutoGenerated'] as bool? ?? false,
      recommendationReason: json['recommendationReason'] as String? ?? '',
      createdAt: (json['createdAt'] as num?)?.toDouble() ?? 0,
      updatedAt: (json['updatedAt'] as num?)?.toDouble() ?? 0,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'userId': userId,
      'name': name,
      'description': description,
      'coverUrl': coverUrl,
      'tracks': tracks.map((t) => t.toJson()).toList(),
      'isAutoGenerated': isAutoGenerated,
      'recommendationReason': recommendationReason,
      'createdAt': createdAt,
      'updatedAt': updatedAt,
    };
  }

  Playlist copyWith({
    String? id,
    String? userId,
    String? name,
    String? description,
    String? coverUrl,
    List<Song>? tracks,
    bool? isAutoGenerated,
    String? recommendationReason,
    double? createdAt,
    double? updatedAt,
  }) {
    return Playlist(
      id: id ?? this.id,
      userId: userId ?? this.userId,
      name: name ?? this.name,
      description: description ?? this.description,
      coverUrl: coverUrl ?? this.coverUrl,
      tracks: tracks ?? this.tracks,
      isAutoGenerated: isAutoGenerated ?? this.isAutoGenerated,
      recommendationReason: recommendationReason ?? this.recommendationReason,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }
}
